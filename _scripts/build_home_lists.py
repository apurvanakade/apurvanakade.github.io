#!/usr/bin/env python3
"""AI-owned pre-render step. Generates _includes/home-lists.html.

Emits two plain text lists for the home page, below the intro:

  1. "Selected projects" -- the projects named in PINNED, in that order, each
     a title and its one-line `description:`.
  2. "Writing" -- the RECENT newest posts in blog/*.qmd, by `date:`, each a
     title and a date. Drafts (blog/drafts/, or `draft: true`) are left out.

No images, no cards, no JavaScript: the home page is meant to be quiet. Both
lists are read straight off disk at render time, so they work offline and in
`quarto preview`.

Never edit _includes/home-lists.html by hand -- it is overwritten on every
render. See CLAUDE.md.
"""
import datetime
import html
import pathlib
import re
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROJECTS = ROOT / "projects"
BLOG = ROOT / "blog"
OUT = ROOT / "_includes" / "home-lists.html"

# Slugs of projects/<slug>.qmd listed, in this order, under "Selected projects".
PINNED = ["visual-math-lab", "monte-carlo-methods"]

# How many posts "Writing" shows.
RECENT = 4


def parse_frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None
    out = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m2 = re.match(r"^(\w[\w-]*):\s*(.*)$", line)
        if m2 and m2.group(2).strip():
            out[m2.group(1)] = m2.group(2).strip().strip('"').strip("'")
    return out


def url(path_str):
    """Percent-encode a site-relative path, in case a filename ever contains a
    space, while leaving the separators alone."""
    return urllib.parse.quote(path_str, safe="/-_.~")


def parse_date(raw):
    """'2023-10-26' (or '10/26/2023', '26-10-2023') -> date; None if unrecognised."""
    if not raw:
        return None
    head = raw.strip().strip('"').split()[0]
    for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%d-%m-%Y"):
        try:
            return datetime.datetime.strptime(head, fmt).date()
        except ValueError:
            continue
    return None


def collect_posts():
    posts = []
    for path in BLOG.glob("*.qmd"):
        if path.name.startswith("_") or path.name == "index.qmd":
            continue
        fm = parse_frontmatter(path)
        if not fm or "title" not in fm or fm.get("draft") == "true":
            continue
        date = parse_date(fm.get("date", ""))
        if date is None:
            print(f"build_home_lists: {path.name}: no usable date; skipping")
            continue
        posts.append({
            "title": fm["title"],
            "href": url(f"blog/{path.stem}.html"),
            "date": date,
        })
    posts.sort(key=lambda p: p["date"], reverse=True)
    return posts[:RECENT]


def collect_projects():
    projects = []
    for slug in PINNED:
        path = PROJECTS / f"{slug}.qmd"
        fm = parse_frontmatter(path) if path.exists() else None
        if not fm or "title" not in fm:
            print(f"build_home_lists: pinned project {slug!r} not found; skipping")
            continue
        projects.append({
            "title": fm["title"],
            "href": url(f"projects/{slug}.html"),
            "desc": fm.get("description", ""),
        })
    return projects


def post_row(p):
    return (
        f'<li class="home-list__item">'
        f'<a href="{html.escape(p["href"])}">{html.escape(p["title"])}</a>'
        f'<time class="home-list__date" datetime="{p["date"].isoformat()}">'
        f'{p["date"].strftime("%b %Y")}</time></li>'
    )


def project_row(p):
    return (
        f'<li class="home-list__item home-list__item--stacked">'
        f'<a href="{html.escape(p["href"])}">{html.escape(p["title"])}</a>'
        f'<span class="home-list__desc">{html.escape(p["desc"])}</span></li>'
    )


TEMPLATE = """<!-- GENERATED by _scripts/build_home_lists.py -- do not edit. See CLAUDE.md. -->
<section class="home-list">
<h2 class="home-list__title">Selected projects</h2>
<ul class="home-list__items">
{projects}
</ul>
<a class="home-list__more" href="projects/">All projects &#8594;</a>
</section>

<section class="home-list">
<h2 class="home-list__title">Writing</h2>
<ul class="home-list__items">
{posts}
</ul>
<a class="home-list__more" href="blog/">All posts &#8594;</a>
</section>
"""


def main():
    posts = collect_posts()
    projects = collect_projects()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        TEMPLATE.format(
            posts="\n".join(post_row(p) for p in posts),
            projects="\n".join(project_row(p) for p in projects),
        ),
        encoding="utf-8",
    )
    print(
        f"build_home_lists: wrote {OUT.relative_to(ROOT)} -- "
        f"{len(posts)} posts, {len(projects)} projects"
    )


if __name__ == "__main__":
    main()
