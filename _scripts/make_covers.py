def winding_number():
    """A closed curve that winds twice around the marked point: the winding
    number, which is where a first algebraic-topology course starts."""
    T = 4 * math.pi                       # two full turns
    pts = []
    for i in range(1201):
        t = T * i / 1200
        r = 0.70 + 0.38 * t / T
        pts.append((r * math.cos(t), r * math.sin(t)))
    pts.append(pts[0])                    # close it with a radial segment, which
                                          # crosses the spiral once and visibly
                                          # makes the curve a single closed loop
    f = fit(pts + [(0, 0)], 150, 118)
    curve = [f(p) for p in pts]
    ox, oy = f((0, 0))
    body = (
        polyline(curve, "#ffffff", 2.6, 0.92)
        + f'<circle cx="{ox:.1f}" cy="{oy:.1f}" r="6" fill="{ACCENT}"/>'
        + f'<circle cx="{ox:.1f}" cy="{oy:.1f}" r="15" fill="none" stroke="{ACCENT}" '
          f'stroke-opacity="0.45" stroke-width="1.5"/>'
    )
    return frame(body, "A closed curve winding twice around a point",
                 "#123c52", "#0d2a3a", "WINDING NUMBER", "n = 2")


def weierstrass():
    """The Weierstrass function: continuous everywhere, differentiable nowhere.
    The example that makes an honours calculus course worth taking."""
    def w(x):
        return sum(0.5 ** n * math.cos(3 ** n * math.pi * x) for n in range(8))
    N = 3000
    pts = [(-2 + 4 * i / N, w(-2 + 4 * i / N)) for i in range(N + 1)]
    f = fit(pts, 168, 96)
    body = (
        f'<path d="M{CX - 175} {CY} H{CX + 175}" stroke="#ffffff" stroke-opacity="0.18" stroke-width="1"/>'
        + polyline([f(p) for p in pts], ACCENT, 1.5, 0.95)
    )
    return frame(body, "The Weierstrass function, continuous but nowhere differentiable",
                 "#1a2c3c", "#101d28", "WEIERSTRASS FUNCTION",
                 "continuous, nowhere differentiable")


def penrose():
    """The Penrose tribar -- three bars of cubes running along the x, y and z
    axes. In isometric projection the lattice point (n, n, n) lands exactly on
    (0, 0, 0), so the far end of the third bar closes onto the start of the
    first and the figure reads as impossible. It is the standard example of a
    class that is locally trivial but globally non-trivial, which is what sheaf
    cohomology measures."""
    L, w = 5.0, 1.0

    def iso(p):
        i, j, k = p
        return ((i - j) * 0.8660254, (i + j) * 0.5 - k)

    # (corner, extent) for the three bars, laid out on the cube lattice
    bars = [
        ((0.0, 0.0, 0.0), (L, w, w)),          # along +x
        ((L - w, w, 0.0), (w, L - w, w)),      # along +y
        ((L - w, L - w, w), (w, w, L - w)),    # along +z
    ]
    corners = []
    for (ox, oy, oz), (dx, dy, dz) in bars:
        for a in (0, 1):
            for b in (0, 1):
                for c in (0, 1):
                    corners.append((ox + a * dx, oy + b * dy, oz + c * dz))
    f = fit([iso(p) for p in corners], 140, 120)

    def face(pts):
        return [f(iso(p)) for p in pts]

    shades = ("#ffffff", "#cfe3ea", "#8fb3c4")
    out = []
    # Draw the +z bar first and the +x bar last: at the impossible joint the
    # near bar must paint over the far one.
    for (ox, oy, oz), (dx, dy, dz) in reversed(bars):
        x1, y1, z1 = ox + dx, oy + dy, oz + dz
        faces = [
            [(x1, oy, oz), (x1, y1, oz), (x1, y1, z1), (x1, oy, z1)],   # +x
            [(ox, y1, oz), (x1, y1, oz), (x1, y1, z1), (ox, y1, z1)],   # +y
            [(ox, oy, z1), (x1, oy, z1), (x1, y1, z1), (ox, y1, z1)],   # +z
        ]
        for shade, quad in zip(shades, faces):
            pts = face(quad)
            d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z"
            out.append(f'<path d="{d}" fill="{shade}" fill-opacity="0.92" '
                       f'stroke="#0d2a3a" stroke-width="2" stroke-linejoin="round"/>')
    return frame("".join(out), "The Penrose impossible tribar",
                 "#2f4a3f", "#16261f", "SHEAF COHOMOLOGY",
                 "locally consistent, globally impossible")


def trefoil():
    """A trefoil knot from its 3D parametrisation. z = -sin(3t) vanishes at the
    six points t = k*pi/3, so those cut the curve into arcs that are each wholly
    above or wholly below the crossings. Casing whole arcs (rather than
    individual segments, whose casings overwrite their neighbours) resolves the
    over- and under-strands correctly."""
    def at(t):
        return (math.sin(t) + 2 * math.sin(2 * t),
                math.cos(t) - 2 * math.cos(2 * t),
                -math.sin(3 * t))

    arcs, M, pad = [], 150, 0.05
    for k in range(6):
        t0, t1 = k * math.pi / 3 - pad, (k + 1) * math.pi / 3 + pad
        arcs.append([at(t0 + (t1 - t0) * i / M) for i in range(M + 1)])

    f = fit([(q[0], q[1]) for a in arcs for q in a], 138, 118)
    out = []
    for arc in sorted(arcs, key=lambda a: sum(q[2] for q in a) / len(a)):
        pts = [f((q[0], q[1])) for q in arc]
        out.append(polyline(pts, "#12202b", 17, 1.0))   # casing cuts the strand behind
        out.append(polyline(pts, ACCENT, 7, 1.0))
    return frame("".join(out), "A trefoil knot diagram",
                 "#1b3140", "#12202b", "KNOTS AND SPACES", "the trefoil")


def icosahedron():
    """A rotated icosahedron: 12 vertices, 30 edges, and the symmetry group
    that makes it a standing example in a course on groups."""
    phi = (1 + 5 ** 0.5) / 2
    verts = []
    for s1 in (-1, 1):
        for s2 in (-1, 1):
            verts += [(0, s1, s2 * phi), (s1, s2 * phi, 0), (s2 * phi, 0, s1)]
    verts = sorted(set(verts))
    edges = []
    for a in range(len(verts)):
        for b in range(a + 1, len(verts)):
            d = sum((verts[a][k] - verts[b][k]) ** 2 for k in range(3))
            if abs(d - 4) < 1e-6:
                edges.append((a, b))
    ax, ay = 0.55, 0.42
    rot = []
    for x, y, z in verts:
        y, z = y * math.cos(ax) - z * math.sin(ax), y * math.sin(ax) + z * math.cos(ax)
        x, z = x * math.cos(ay) + z * math.sin(ay), -x * math.sin(ay) + z * math.cos(ay)
        rot.append((x, y, z))
    f = fit([(p[0], p[1]) for p in rot], 128, 118)
    proj = [f((p[0], p[1])) for p in rot]
    out = []
    for a, b in sorted(edges, key=lambda e: (rot[e[0]][2] + rot[e[1]][2]) / 2):
        near = (rot[a][2] + rot[b][2]) / 2 > 0
        out.append(polyline([proj[a], proj[b]], "#ffffff",
                            2.4 if near else 1.4, 0.95 if near else 0.30))
    for (x, y), v in zip(proj, rot):
        if v[2] > 0:
            out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4" fill="{ACCENT}"/>')
    return frame("".join(out), "An icosahedron wireframe",
                 "#3b3663", "#211d3a", "SYMMETRY GROUPS", "the icosahedron")


def riemann_sqrt():
    """The Riemann surface of the square root, drawn as the graph of Re(w) over
    z = w^2: the sheet that has to pass through itself because the square root
    needs two of them."""
    def pt(rho, th):
        z_re = rho * rho * math.cos(2 * th)
        z_im = rho * rho * math.sin(2 * th)
        h = rho * math.cos(th)
        return (z_re - 0.5 * z_im, -1.05 * h + 0.42 * z_im)

    curves = []
    for n in range(9):                       # constant rho
        rho = 0.22 + 0.78 * n / 8
        curves.append(([pt(rho, 2 * math.pi * i / 220) for i in range(221)], 0.55))
    for n in range(24):                      # constant theta
        th = 2 * math.pi * n / 24
        curves.append(([pt(0.16 + 0.84 * i / 40, th) for i in range(41)], 0.30))
    f = fit([p for c, _ in curves for p in c], 150, 118)
    body = "".join(polyline([f(p) for p in c], "#ffffff", 1.5, op) for c, op in curves)
    return frame(body, "The Riemann surface of the square root",
                 "#14535e", "#0b2a30", "RIEMANN SURFACES", "the square root, two sheets")


def potato():
    """A closed curve with its osculating circle at the point of highest
    curvature -- the honest answer to how curved a potato is."""
    def r(t):
        return 1 + 0.16 * math.cos(2 * t + 0.7) + 0.09 * math.cos(3 * t - 1.1) \
                 + 0.05 * math.cos(5 * t + 0.3)
    N = 720
    raw = [(r(2 * math.pi * i / N) * math.cos(2 * math.pi * i / N),
            r(2 * math.pi * i / N) * math.sin(2 * math.pi * i / N)) for i in range(N + 1)]
    f = fit(raw, 132, 112)
    pts = [f(p) for p in raw]

    # discrete curvature from the circumradius of three consecutive samples
    best, best_k = 0, 0.0
    for i in range(4, N - 4, 2):
        (x1, y1), (x2, y2), (x3, y3) = pts[i - 4], pts[i], pts[i + 4]
        a = math.dist((x1, y1), (x2, y2)); b = math.dist((x2, y2), (x3, y3))
        c = math.dist((x1, y1), (x3, y3))
        area = abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2
        if area > 1e-9:
            k = 4 * area / (a * b * c)
            if k > best_k:
                best_k, best = k, i
    px, py = pts[best]
    ax_, ay_ = pts[best - 4]; bx, by = pts[best + 4]
    tx, ty = bx - ax_, by - ay_
    n = math.hypot(tx, ty) or 1
    nx, ny = -ty / n, tx / n
    cxx, cyy = CX - px, CY - py                     # inward test
    if nx * cxx + ny * cyy < 0:
        nx, ny = -nx, -ny
    R = 1 / best_k
    body = (
        polyline(pts, "#ffffff", 2.6, 0.9, fill="rgba(255,255,255,0.06)")
        + f'<circle cx="{px + nx * R:.1f}" cy="{py + ny * R:.1f}" r="{R:.1f}" fill="none" '
          f'stroke="{ACCENT}" stroke-opacity="0.75" stroke-width="2" stroke-dasharray="5 5"/>'
        + f'<circle cx="{px:.1f}" cy="{py:.1f}" r="5" fill="{ACCENT}"/>'
    )
    return frame(body, "A closed curve with its osculating circle",
                 "#6b4226", "#38210f", "CURVATURE", "the osculating circle, r = 1/k")


def bell_curve():
    """Gauss's route to the normal distribution: noisy measurements, and the
    curve that least squares forces on their errors. Heights are negated
    because SVG's y axis points down."""
    rng = __import__("random").Random(20260907)

    def g(x):
        return math.exp(-x * x / 2)

    N, LO, HI = 400, -3.4, 3.4
    curve = [(LO + (HI - LO) * i / N, -g(LO + (HI - LO) * i / N)) for i in range(N + 1)]
    f = fit(curve + [(LO, 0.0), (HI, 0.0)], 158, 100)

    body = []
    ax0, ay0 = f((LO, 0.0))
    ax1, _ = f((HI, 0.0))
    body.append(f'<path d="M{ax0:.1f} {ay0:.1f} H{ax1:.1f}" stroke="#ffffff" '
                f'stroke-opacity="0.20" stroke-width="1"/>')
    for _ in range(170):                     # measurements scattered under the curve
        x = rng.gauss(0, 1)
        if not LO < x < HI:
            continue
        px, py = f((x, -g(x) * rng.random()))
        body.append(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="2.6" '
                    f'fill="#ffffff" fill-opacity="0.38"/>')
    body.append(polyline([f(p) for p in curve], ACCENT, 3.0, 0.95))
    return frame("".join(body), "A Gaussian curve over scattered measurements",
                 "#7a3b52", "#3a1c28", "LEAST SQUARES", "e^(-x&#178;/2)")


