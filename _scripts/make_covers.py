def polyline(pts, stroke="#ffffff", width=2.4, opacity=1.0, fill="none"):
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts)
    return (f'<path d="{d}" fill="{fill}" stroke="{stroke}" stroke-width="{width}" '
            f'stroke-opacity="{opacity}" stroke-linecap="round" stroke-linejoin="round"/>')


def fit(pts, half_w, half_h):
    """Scale/translate projected points to sit centred on (CX, CY)."""
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    sx = (max(xs) - min(xs)) or 1.0
    sy = (max(ys) - min(ys)) or 1.0
    k = min(2 * half_w / sx, 2 * half_h / sy)
    mx, my = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    return lambda p: (CX + (p[0] - mx) * k, CY + (p[1] - my) * k)


