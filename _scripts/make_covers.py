def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def tspans(title, fs):
    words, lines, cur = title.split(), [], ""
    for w in words:
        if len(cur + " " + w) > 15 and cur:
            lines.append(cur); cur = w
        else:
            cur = (cur + " " + w).strip()
    lines.append(cur)
    return "".join(
        f'<tspan x="400" dy="{0 if i == 0 else fs * 1.15}">{esc(l)}</tspan>'
        for i, l in enumerate(lines)
    ), len(lines)

